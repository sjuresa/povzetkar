package com.povzetkar.quarkus.api.dto;

import org.eclipse.microprofile.openapi.annotations.media.Schema;
import java.time.LocalDate;

@Schema(name = "Summary", description = "Represents an individual content piece summary generated by AI.")
public record SummaryDTO(
        Long id,
        @Schema(description = "The title of the associated content item.")
        String title,
        @Schema(description = "The original URL of the content.")
        String sourceUrl,
        @Schema(description = "The full AI-generated summary text in Markdown format.")
        String summaryText,
        @Schema(description = "Shortened 'TL;DR' extracted summary.")
        String executiveSummary,
        LocalDate briefingDate,
        @Schema(description = "The publication date/time of the original content.")
        java.time.Instant publishedAt,
        @Schema(description = "Duration in seconds (if applicable).")
        Long durationSeconds,
        @Schema(description = "The platform of the content (e.g., YOUTUBE, BLOG).")
        String platform,
        @Schema(description = "The name of the author or content creator.")
        String authorName,
        @Schema(description = "Human-readable formatted duration (e.g., 12m 45s).")
        String formattedDuration,
        @Schema(description = "The public UUID for sharing, null if not shared.")
        String uuid
) {
}
