-- V23: Create Job Execution Audit Table
-- This table stores historical transitions for both high-level jobs and individual item processing.

CREATE TABLE job_execution_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id UUID,
    content_item_id BIGINT,
    item_title VARCHAR(1024),
    status VARCHAR(50) NOT NULL,
    message TEXT,
    correlation_id VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Indices for performance
CREATE INDEX idx_job_audit_job_id ON job_execution_audit(job_id);
CREATE INDEX idx_job_audit_item_id ON job_execution_audit(content_item_id);
CREATE INDEX idx_job_audit_correlation_id ON job_execution_audit(correlation_id);
CREATE INDEX idx_job_audit_created_at ON job_execution_audit(created_at);

-- Foreign keys (optional, but good for integrity)
-- Note: BackgroundJob uses UUID as PK.
ALTER TABLE job_execution_audit ADD CONSTRAINT fk_job_audit_job FOREIGN KEY (job_id) REFERENCES background_jobs(job_id) ON DELETE SET NULL;
ALTER TABLE job_execution_audit ADD CONSTRAINT fk_job_audit_item FOREIGN KEY (content_item_id) REFERENCES content_items(id) ON DELETE SET NULL;
