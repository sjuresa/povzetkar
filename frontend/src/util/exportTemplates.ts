/**
 * Utility for generating various export formats (HTML, etc.) for briefings.
 */

interface BriefingExportData {
  title: string;
  topicName: string;
  briefingDate: string;
  summaryHtml: string;
  contentHtml: string;
}

/**
 * Generates a full HTML document for a briefing, optimized for black and white printing.
 */
export function generateBriefingHtml({
  title,
  topicName,
  briefingDate,
  summaryHtml,
  contentHtml
}: BriefingExportData): string {
  const generationDate = new Date().toLocaleDateString();

  return `
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>${title}</title>
    <style>
        @page { size: A4; margin: 20mm; }
        body { 
            font-family: 'Times New Roman', Times, serif; 
            line-height: 1.5; 
            color: #000; 
            max-width: 800px; 
            margin: 0 auto; 
            padding: 0;
            background-color: #fff;
        }
        h1 { font-size: 24pt; margin-top: 0; margin-bottom: 5pt; color: #000; border-bottom: 1pt solid #000; padding-bottom: 5pt; }
        .metadata { color: #555; font-style: italic; margin-bottom: 20pt; font-size: 10pt; font-family: sans-serif; }
        .summary-box { border: 1pt solid #000; padding: 15pt; margin-bottom: 20pt; background: #fff; }
        .summary-title { font-weight: bold; margin-bottom: 5pt; font-family: sans-serif; text-transform: uppercase; font-size: 9pt; letter-spacing: 0.5pt; }
        h2 { font-size: 16pt; color: #000; margin-top: 25pt; border-bottom: 0.5pt solid #ccc; padding-bottom: 3pt; }
        p { margin-bottom: 10pt; text-align: justify; }
        ul, ol { margin-bottom: 10pt; padding-left: 20pt; }
        li { margin-bottom: 5pt; }
        hr { border: 0; border-top: 0.5pt solid #000; margin: 30pt 0; }
        .footer { text-align: center; color: #777; font-size: 8pt; margin-top: 40pt; font-family: sans-serif; border-top: 0.5pt solid #ddd; padding-top: 10pt; }
        @media print {
            body { max-width: 100%; margin: 0; }
            .no-print { display: none; }
        }
    </style>
</head>
<body>
    <h1>${title}</h1>
    <div class="metadata">
        Topic: ${topicName} | Date: ${briefingDate}
    </div>
    
    <div class="summary-box">
        <div class="summary-title">Executive Summary</div>
        ${summaryHtml}
    </div>

    <div class="content">
        ${contentHtml}
    </div>
    
    <div class="footer">
        Generated by Povzetkar | ${generationDate}
    </div>
</body>
</html>`.trim();
}

/**
 * Generates Markdown content for a briefing.
 */
export function generateBriefingMarkdown({
  title,
  topicName,
  briefingDate,
  metaSummary,
  content
}: {
  title: string;
  topicName: string;
  briefingDate: string;
  metaSummary: string;
  content: string;
}): string {
  return `# ${title}

**Topic:** ${topicName}
**Date:** ${briefingDate}

## Executive Summary

${metaSummary}

---

${content}`.trim();
}
